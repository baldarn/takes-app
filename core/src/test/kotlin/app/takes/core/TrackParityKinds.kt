    /** The kinds that account for [signature] in a call of [function] that falls on [tags], and what none of them accounts for. */
    fun explain(function: String, tags: Set<String>, signature: Set<String>): Pair<List<String>, Set<String>> {
        val left = LinkedHashSet(signature)
        val found = ArrayList<String>()
        for (kind in all) {
            if (left.isEmpty()) break
            if (kind.functions != null && function !in kind.functions) continue
            if (kind.tags.isNotEmpty() && kind.tags.none { it in tags }) continue
            if (kind.aspects.none { it in left }) continue
            left -= kind.aspects
            found += kind.id
        }
        return found to left
    }
