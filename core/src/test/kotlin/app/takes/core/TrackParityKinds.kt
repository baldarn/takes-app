/**
 * One kind of difference between a function of today and the same edit made
 * through the track model: what each does, what a user would see of it, and
 * the lines of the original the track model follows.
 *
 * A kind explains a call when the call is one of its [functions] (all, when
 * null), falls where its [tags] say (anywhere, when empty), and differs in
